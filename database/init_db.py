from database.conexao import conectar


def criar_banco():
    conexao = conectar()
    cursor = conexao.cursor()

    cursor.execute("""
        CREATE TABLE IF NOT EXISTS duplas (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            participante_1 TEXT NOT NULL,
            participante_2 TEXT NOT NULL,
            senha_hash TEXT NOT NULL,
            criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )""")

    cursor.execute("""
        CREATE TABLE IF NOT EXISTS perguntas (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            enunciado TEXT NOT NULL,
            alternativa_a TEXT NOT NULL,
            alternativa_b TEXT NOT NULL,
            alternativa_c TEXT NOT NULL,
            alternativa_d TEXT NOT NULL,
            alternativa_e TEXT NOT NULL,
            alternativa_correta TEXT NOT NULL,
            area TEXT NOT NULL DEFAULT 'LC',
            tipo TEXT NOT NULL DEFAULT 'PRINCIPAL',
            ordem INTEGER NOT NULL DEFAULT 1,
            ativa INTEGER NOT NULL DEFAULT 1,
            imagem TEXT
        )""")

    for area in ("LC", "CH", "CN", "MT"):
        for tipo in ("PRINCIPAL", "RESERVA"):
            cursor.execute(
                """
                SELECT id
                FROM perguntas
                WHERE area = %s AND tipo = %s
                ORDER BY ordem, id
                """,
                (area, tipo),
            )

            perguntas = cursor.fetchall()

            for ordem, pergunta in enumerate(perguntas, start=1):
                cursor.execute(
                    """
                    UPDATE perguntas
                    SET ordem = %s
                    WHERE id = %s
                    """,
                    (ordem, pergunta["id"]),
                )

    cursor.execute("""
        CREATE UNIQUE INDEX IF NOT EXISTS ux_perguntas_area_tipo_ordem
        ON perguntas(area, tipo, ordem)
    """)

    cursor.execute("""
        CREATE TABLE IF NOT EXISTS respostas (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            dupla_id INTEGER NOT NULL,
            pergunta_id INTEGER NOT NULL,
            alternativa_escolhida TEXT NOT NULL,
            correta INTEGER NOT NULL,
            pontos INTEGER NOT NULL DEFAULT 0,
            respondida_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            fase TEXT NOT NULL DEFAULT 'REGULAR',
            rodada_desempate INTEGER,

            FOREIGN KEY (dupla_id)
                REFERENCES duplas(id),

            FOREIGN KEY (pergunta_id)
                REFERENCES perguntas(id),

            UNIQUE (dupla_id, pergunta_id)
        )""")

    cursor.execute("""
        UPDATE respostas
        SET fase = 'REGULAR'
        WHERE fase IS NULL OR fase = ''
    """)

    cursor.execute("""
        CREATE TABLE IF NOT EXISTS configuracoes (
            id INTEGER PRIMARY KEY,
            ranking_liberado INTEGER NOT NULL DEFAULT 0,
            etapa_ativa INTEGER NOT NULL DEFAULT 0
        )""")

    cursor.execute("""
        ALTER TABLE configuracoes
        DROP COLUMN IF EXISTS ranking_etapa
    """)

    cursor.execute("""
        INSERT INTO configuracoes (
            id,
            ranking_liberado,
            etapa_ativa
        )
        VALUES (1, 0, 0)
        ON CONFLICT (id) DO NOTHING
    """)

    cursor.execute("""
        CREATE TABLE IF NOT EXISTS desempates (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            pontos_regulares INTEGER NOT NULL,
            status TEXT NOT NULL DEFAULT 'PENDENTE',
            vencedor_dupla_id INTEGER,
            criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

            FOREIGN KEY (vencedor_dupla_id)
                REFERENCES duplas(id)
        )""")

    cursor.execute("""
        CREATE TABLE IF NOT EXISTS desempate_membros (
            desempate_id INTEGER NOT NULL,
            dupla_id INTEGER NOT NULL,
            status TEXT NOT NULL DEFAULT 'ATIVA',
            eliminada_rodada INTEGER,

            PRIMARY KEY (desempate_id, dupla_id),

            FOREIGN KEY (desempate_id)
                REFERENCES desempates(id),

            FOREIGN KEY (dupla_id)
                REFERENCES duplas(id)
        )""")

    cursor.execute("""
        CREATE TABLE IF NOT EXISTS desempate_rodadas (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            desempate_id INTEGER NOT NULL,
            numero INTEGER NOT NULL,
            area TEXT NOT NULL,
            pergunta_id INTEGER NOT NULL,
            status TEXT NOT NULL DEFAULT 'ABERTA',
            criada_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

            UNIQUE (desempate_id, numero),
            UNIQUE (pergunta_id),

            FOREIGN KEY (desempate_id)
                REFERENCES desempates(id),

            FOREIGN KEY (pergunta_id)
                REFERENCES perguntas(id)
        )""")

    conexao.commit()
    cursor.close()
    conexao.close()


if __name__ == "__main__":
    criar_banco()
    print("Banco PostgreSQL atualizado com sucesso.")